def test_miss_budget_pools_by_pixel_not_by_averaging_shares():
    """A 10,000-pixel event must not weigh the same as a 100-pixel one."""
    big = _fake("big", "flood", 10000, {dx.MISS_CAUSES[5]: 10000})
