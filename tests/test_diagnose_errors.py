"""The error diagnosis, on a SYNTHETIC event with known truth.

SYNTHETIC: the valley, the flood, the debris fan and the bait patch are
generated by tests/conftest.py, so every number here tests the diagnosis logic
and is never real-world accuracy (Rule 3.8). The real dev-event numbers live in
docs/accuracy_diagnosis.md, each traceable to a score file.

What is established here:
  - `stages()` is a FAITHFUL replica of strandline.detect.detect_flood: the
    class map it rebuilds is identical to the real one, in both modes, with and
    without optical evidence. Everything else in the module rests on that, so
    it is the first test and the module refuses to report when it fails.
  - the miss and false-alarm attributions PARTITION their error set: every
    pixel is counted once, and the shares sum to 1.
  - a brightening flood missed by `darkening` mode is attributed to "no change
    signal", not to terrain - the diagnosis names the right cause for the one
    failure mode whose cause is already known.
  - the shift scan finds a shift that was really applied, and the oracle bound
    agrees with validation/compare.py rather than computing its own metric.
"""

from __future__ import annotations

from types import SimpleNamespace

import numpy as np
import pytest

from eval import diagnose_errors as dx
from strandline.config import (
    FUSION_OFF,
    FUSION_UNION,
    MODE_DARKENING,
    MODE_ROUGH_WATER,
    DetectParams,
    ExtentParams,
    RunParams,
)
from validation import compare

DARKENS = -10.0
BRIGHTENS = 6.0


def make_scene(scene_data, optical=None):
    """A duck-typed stand-in for strandline.run.PreparedScene."""
    g = scene_data["geometry"]
    return SimpleNamespace(
        pre_vv_db=np.stack([p[0] for p in scene_data["pre"]]),
        pre_vh_db=np.stack([p[1] for p in scene_data["pre"]]),
        post_vv_db=scene_data["post"][0],
        post_vh_db=scene_data["post"][1],
        terrain=SimpleNamespace(hand_m=g["hand"].astype(float),
                                slope_deg=scene_data["slope"],
                                streams=g["streams"]),
        optical_evidence=optical,
    )


# --- the replica is faithful, which everything else depends on ----------------

@pytest.mark.parametrize("mode,delta", [(MODE_DARKENING, DARKENS),
                                        (MODE_ROUGH_WATER, DARKENS),
                                        (MODE_ROUGH_WATER, BRIGHTENS)])
def test_stages_rebuilds_the_real_class_map_exactly(scene, mode, delta):
    data = scene(flood_delta_db=delta)
    st = dx.stages(make_scene(data), DetectParams(mode=mode))
    assert st.faithful
    assert np.array_equal(st.classes, st.classes_authoritative)


def test_stages_is_faithful_with_optical_evidence_fused(scene):
    """Optical union changes the class map; the replica must follow it."""
    data = scene(flood_delta_db=DARKENS)
    g = data["geometry"]
    water = np.zeros(g["flood"].shape, dtype=bool)
    water[90:110, 100:112] = True          # an optical-only water patch
    debris = np.zeros_like(water)
    debris[196:210, 108:126] = True
    evidence = SimpleNamespace(water=water, debris=debris,
                               clear=np.ones_like(water), fusion=FUSION_UNION)
    st = dx.stages(make_scene(data, evidence), DetectParams())
    assert st.faithful
    assert st.opt_water.any(), "the optical patch should have reached the water channel"

    off = SimpleNamespace(water=water, debris=debris,
                          clear=np.ones_like(water), fusion=FUSION_OFF)
    st_off = dx.stages(make_scene(data, off), DetectParams())
    assert st_off.faithful
    assert not st_off.opt_water.any()


# --- the attributions partition the error -------------------------------------

def _diagnose(data, mode, truth, optical=None, ep=None):
    dp = DetectParams(mode=mode)
    sc = make_scene(data, optical)
    st = dx.stages(sc, dp)
    classes = st.classes_authoritative
    domain = compare.scoring_domain(classes)
    ep = ep if ep is not None else ExtentParams()
    pred = compare.flood_affected_mask(classes, include_debris=ep.debris_in_flood_extent)
    ref = truth & domain
    missed = ref & ~pred
    false_px = pred & ~ref & domain
    pl = dx.places(st, sc, dp)
    return st, pred, ref, domain, missed, false_px, dx.attribute_misses(st, missed, dp, ep), \
        dx.attribute_false_alarms(st, false_px, pl)


def _reference_like_a_real_one(g):
    """What an expert reference actually looks like: water PLUS mass movement,
    and polygons that run onto ground the detector is not allowed to classify.
    Every dev-event reference is scored as that union (validation/compare.py)."""
    return g["flood"] | g["debris"] | g["bait"]


def test_miss_attribution_counts_every_missed_pixel_exactly_once(scene):
    data = scene(flood_delta_db=DARKENS)
    truth = _reference_like_a_real_one(data["geometry"])
    st, pred, ref, domain, missed, _fp, causes, _places = _diagnose(data, MODE_ROUGH_WATER, truth)
    assert missed.any(), "the synthetic event should leave some misses to attribute"
    assert sum(int(m.sum()) for m in causes.values()) == int(missed.sum())
    stacked = np.sum([m.astype(int) for m in causes.values()], axis=0)
    assert stacked.max() <= 1, "a missed pixel was attributed to two causes"
    assert set(causes) == set(dx.MISS_CAUSES)


def test_false_alarm_attribution_counts_every_false_pixel_exactly_once(scene):
    data = scene(flood_delta_db=DARKENS)
    truth = data["geometry"]["flood"]
    st, pred, ref, domain, _missed, false_px, _c, places_hit = _diagnose(
        data, MODE_ROUGH_WATER, truth)
    assert sum(int(m.sum()) for m in places_hit.values()) == int(false_px.sum())
    stacked = np.sum([m.astype(int) for m in places_hit.values()], axis=0)
    assert stacked.max() <= 1
    assert set(places_hit) == set(dx.FP_PLACES)


def test_nothing_is_left_unexplained_on_the_synthetic_event(scene):
    """`unexplained` is a residual bucket; it must stay empty while the replica
    matches the detector. A non-zero count means a stage is unaccounted for."""
    for delta in (DARKENS, BRIGHTENS):
        data = scene(flood_delta_db=delta)
        truth = _reference_like_a_real_one(data["geometry"])
        _st, _p, _r, _d, _m, _f, causes, _pl = _diagnose(data, MODE_ROUGH_WATER, truth)
        assert int(causes["unexplained"].sum()) == 0, f"delta {delta}"


# --- the named cause is the right one -----------------------------------------

def test_a_brightening_flood_under_darkening_mode_is_blamed_on_the_right_rule(scene):
    """The one failure mode whose cause is already known, used as the check.

    `darkening` requires water to get DARKER. A flood that BRIGHTENS is not
    invisible to it - it is classified, as debris, and then kept out of the
    flood extent by ExtentParams.debris_in_flood_extent. So the honest cause is
    the debris rule, on analysed ground, and the diagnosis must say that rather
    than blaming terrain or a missing signal. Flipping that one flag recovers
    most of it, which is the proof the attribution named the real blocker.
    """
    data = scene(flood_delta_db=BRIGHTENS)
    truth = data["geometry"]["flood"]
    _st, _p, _r, _d, missed, _f, causes, _pl = _diagnose(data, MODE_DARKENING, truth)
    shares = {k: int(v.sum()) / int(missed.sum()) for k, v in causes.items()}
    top = max(shares, key=shares.get)
    assert top == dx.MISS_CAUSES[3], shares
    assert shares[top] > 0.8, shares
    terrain_share = shares[dx.MISS_CAUSES[0]] + shares[dx.MISS_CAUSES[1]]
    assert terrain_share < 0.05, shares

    debris_in = ExtentParams(debris_in_flood_extent=True)
    _s2, _p2, _r2, _d2, missed_in, _f2, _c2, _pl2 = _diagnose(
        data, MODE_DARKENING, truth, ep=debris_in)
    assert int(missed_in.sum()) < 0.2 * int(missed.sum())


def test_rough_water_mode_finds_that_same_flood(scene):
    """The contrast that makes the previous test mean something."""
    data = scene(flood_delta_db=BRIGHTENS)
    truth = data["geometry"]["flood"]
    _st, _p, _r, _d, missed, _f, _c, _pl = _diagnose(data, MODE_ROUGH_WATER, truth)
    assert int(missed.sum()) / int(truth.sum()) < 0.5


# --- boundary and shift -------------------------------------------------------

def test_boundary_profile_puts_a_one_pixel_rim_within_one_pixel():
    ref = np.zeros((60, 60), dtype=bool)
    ref[20:40, 20:40] = True
    pred = np.zeros_like(ref)
    pred[21:39, 21:39] = True            # eroded by one pixel: a pure rim miss
    domain = np.ones_like(ref)
    prof = dx.boundary_profile(pred, ref, domain)
    assert prof["fp"] == 0
    assert prof["fn"] > 0
    # Distances are Euclidean, so a rim CORNER is sqrt(2) px from the nearest
    # true positive: within 3 px is the share that must be exactly 1.
    assert prof["fn_within_1px"] > 0.9
    assert prof["fn_within_3px"] == 1.0
    assert prof["errors_within_3px_of_a_correct_detection"] == 1.0


def test_shift_scan_recovers_a_shift_that_was_really_applied():
    ref = np.zeros((80, 80), dtype=bool)
    ref[30:50, 30:50] = True
    pred = np.zeros_like(ref)
    pred[33:53, 32:52] = True            # our map sits 3 rows down, 2 cols right
    out = dx.shift_scan(pred, ref, np.ones_like(ref), max_shift=5)
    assert (out["best"]["dy"], out["best"]["dx"]) == (-3, -2)
    assert out["best"]["f1"] == pytest.approx(1.0)
    assert out["gain_from_best_shift"] > 0


def test_shift_scan_reports_no_gain_when_the_maps_already_line_up():
    ref = np.zeros((80, 80), dtype=bool)
    ref[30:50, 30:50] = True
    out = dx.shift_scan(ref.copy(), ref, np.ones_like(ref), max_shift=5)
    assert (out["best"]["dy"], out["best"]["dx"]) == (0, 0)
    assert out["gain_from_best_shift"] == 0.0


# --- the oracle bound uses the project's own metric ---------------------------

def test_upper_bound_baseline_is_the_measured_metric_not_a_new_one(scene):
    data = scene(flood_delta_db=DARKENS)
    truth = _reference_like_a_real_one(data["geometry"])
    _st, pred, ref, domain, _m, _f, causes, places_hit = _diagnose(
        data, MODE_ROUGH_WATER, truth)
    bounds = dx.upper_bounds(pred, ref, domain, causes, places_hit, tolerance_px=1)
    expected = compare.flood_metrics(pred, ref, domain, 1)["f1_tolerant"]
    assert bounds["baseline_f1_tolerant"] == expected
    for info in bounds["if_fixed"].values():
        assert info["gain"] >= -1e-9, "an oracle fix can never lower the score"


def test_recovering_every_miss_cause_gives_perfect_recall(scene):
    data = scene(flood_delta_db=DARKENS)
    truth = _reference_like_a_real_one(data["geometry"])
    _st, pred, ref, domain, missed, _f, causes, _pl = _diagnose(
        data, MODE_ROUGH_WATER, truth)
    all_causes = np.zeros_like(missed)
    for m in causes.values():
        all_causes |= m
    assert compare.flood_metrics(pred | all_causes, ref, domain, 0)["recall"] == 1.0


