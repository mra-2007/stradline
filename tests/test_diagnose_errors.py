def _table_blocks(text):
    blocks, cur = [], []
    for line in text.splitlines():
        if line.startswith("|"):
            cur.append(line)
        elif cur:
            blocks.append(cur)
            cur = []
    if cur:
        blocks.append(cur)
    return blocks


def _cell_count(line):
    """Cells in a markdown row, counting an escaped pipe as content."""
    return len(line.replace("\\|", "\x01").split("|")) - 2


def test_rendered_tables_are_rectangular():
    """A cause name containing a pipe once shifted every column to its right.

    The renderer escapes them now; this fails if that ever regresses, on a
    document built from a recorded diagnosis rather than from rasters.
    """
    diags = [_fake("steep", "flood", 100, {dx.MISS_CAUSES[5]: 60, dx.MISS_CAUSES[6]: 40},
                   sub={"no_signal_pixels": 60, "gate_pixels": 40,
                        "gate_blocked_by_vh_alone": 10},
                   fp=10, places={dx.FP_PLACES[2]: 10}),
             _fake("a_control", "control", 1, {}, fp=20, places={dx.FP_PLACES[0]: 20})]
    diags[0].bounds = {"baseline_f1_tolerant": 0.5,
                       "if_fixed": {f"recover {dx.MISS_CAUSES[5]}":
                                    {"pixels": 60, "f1_tolerant": 0.8, "gain": 0.3}}}
    events = {"steep": {"terrain": "mean slope 20.0 deg"},
              "a_control": {"terrain": "mean slope 20.0 deg"}}
    text = dx.render_markdown("20260101T000000Z", diags,
                              [{"key": "run.n_pre", "shipped_default": 5,
                                "scored": [{"value": 3, "events": ["steep"]}]}],
                              1, "2026-01-01", events=events)
    assert dx.MISS_CAUSES[5] in text.replace("\\|", "|")
    blocks = _table_blocks(text)
    assert blocks, "the document should contain tables"
    for block in blocks:
        widths = {_cell_count(line) for line in block}
        assert len(widths) == 1, (sorted(widths), block[0][:90])


