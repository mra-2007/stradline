    assert budget["by_cause_share"][dx.MISS_CAUSES[5]] == pytest.approx(10000 / 10100, abs=1e-4)
    assert budget["by_cause_share"][dx.MISS_CAUSES[6]] == pytest.approx(100 / 10100, abs=1e-4)


