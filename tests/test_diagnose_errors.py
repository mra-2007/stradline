def test_detect_params_in_this_module_only_come_from_score_files_or_defaults():
    """A guard with teeth: every DetectParams/RunParams built here is built
    either from a score file's dict or with no arguments at all."""
    import ast
    tree = ast.parse(open(dx.__file__, encoding="utf-8").read())
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call) or not isinstance(node.func, ast.Name):
            continue
        if node.func.id not in {"DetectParams", "RunParams", "OpticalParams", "ExtentParams"}:
            continue
        only_kwargs_from_a_dict = all(k.arg is None for k in node.keywords)
        assert not node.args and (not node.keywords or only_kwargs_from_a_dict), (
            f"{node.func.id} built with explicit values at line {node.lineno}: a diagnosis "
            f"must not set a parameter")


